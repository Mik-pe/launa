/// Configuration for fault log responses generated by the spa simulator.
///
/// When set on `SpaSim`, the `generate_fault_log_response()` method will produce
/// frames encoding these values instead of the default hardcoded data.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FaultLogConfig {
    /// Total number of faults recorded.
    pub fault_count: u8,
    /// This entry's number.
    pub entry_number: u8,
    /// Fault code identifying the type of fault.
    pub message_code: FaultCode,
    /// How many days ago the fault occurred.
    pub days_ago: u8,
    /// Hour the fault occurred (0-23).
    pub hour: u8,
    /// Minute the fault occurred (0-59).
    pub minute: u8,
    /// Flags (heating mode, temp range).
    pub flags: u8,
    /// Set temperature at time of fault.
    pub set_temperature: u8,
    /// Sensor A temperature at time of fault.
    pub sensor_a_temp: u8,
    /// Sensor B temperature at time of fault.
    pub sensor_b_temp: u8,
}

